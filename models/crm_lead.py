from odoo import models, fields, api


class CrmLead(models.Model):
    _inherit = 'crm.lead'

    # ── ML Scoring ──────────────────────────────────────────────────────
    ml_probability = fields.Float(
        string='ML Probability (%)',
        default=0.0,
        tracking=True,
        help='Conversion probability predicted by the LightGBM model.',
    )
    manual_score = fields.Integer(
        string='Manual Score',
        default=0,
        help='Baseline heuristic score (0-100) before ML adjustment.',
    )
    ai_explanation = fields.Text(
        string='AI Insight',
        readonly=True,
        help='Explainability note generated by the scoring engine.',
    )

    # ── Qualification (populated by the Demo form) ──────────────────────
    x_job_seniority = fields.Selection(
        [
            ('c_level', 'C-Level / VP / Founder'),
            ('director', 'Director'),
            ('manager', 'Manager'),
            ('individual', 'Engineer / Contributor'),
            ('other', 'Other'),
        ],
        string='Job Seniority',
    )
    x_company_size = fields.Selection(
        [
            ('1_10', '1 - 10 employees'),
            ('11_50', '11 - 50 employees'),
            ('51_250', '51 - 250 employees'),
            ('251_1000', '251 - 1000 employees'),
            ('1000_plus', '1000+ employees'),
        ],
        string='Company Size',
    )
    lead_role = fields.Selection(
        [
            ('c_level', 'C-Level / VP / Founder'),
            ('director', 'Director'),
            ('manager', 'Manager'),
            ('individual', 'Engineer / Contributor'),
            ('other', 'Other'),
        ],
        string='Job Seniority (Alias)',
    )
    company_size = fields.Selection(
        [
            ('1_10', '1 - 10 employees'),
            ('11_50', '11 - 50 employees'),
            ('51_250', '51 - 250 employees'),
            ('251_1000', '251 - 1000 employees'),
            ('1000_plus', '1000+ employees'),
        ],
        string='Company Size (Alias)',
    )
    industry = fields.Selection(
        [
            ('it_offshoring', 'IT & Offshoring'),
            ('fintech_banking', 'Banking & FinTech'),
            ('telecom', 'Telecommunications'),
            ('manufacturing', 'Manufacturing & Logistics'),
            ('healthcare', 'Healthcare & Pharma'),
            ('other', 'Other'),
        ],
        string='Industry Vertical',
    )
    existing_crm = fields.Selection(
        [
            ('odoo', 'Odoo CRM (Native)'),
            ('salesforce', 'Salesforce'),
            ('hubspot', 'HubSpot'),
            ('custom', 'Custom Internal CRM'),
            ('other', 'Other / None'),
        ],
        string='Current CRM Stack',
    )

    # ── Behavioral Telemetry ────────────────────────────────────────────
    x_pricing_views = fields.Integer(
        string='Pricing Page Visits',
        default=0,
        help='Number of times prospect viewed the pricing page.',
    )
    x_time_on_site = fields.Integer(
        string='Time on Site (seconds)',
        default=0,
        help='Total session duration on site in seconds.',
    )
    visited_pricing_page = fields.Boolean(
        string='Visited Pricing Page',
        default=False,
    )
    pricing_page_time = fields.Integer(
        string='Time on Pricing Page (s)',
        default=0,
        help='Seconds the prospect spent on the pricing page.',
    )
    downloaded_report = fields.Boolean(
        string='Downloaded Benchmark Report',
        default=False,
        help='Prospect downloaded the 2026 Enterprise RevOps Benchmark Report.',
    )

    # ── Compliance ──────────────────────────────────────────────────────
    cndp_consent = fields.Boolean(
        string='CNDP Consent (Law 09-08)',
        default=False,
        help='Prospect agreed to data processing under Moroccan CNDP Law 09-08.',
    )

    # ── Auto-set native priority stars when ml_probability is written ───
    def write(self, vals):
        if 'ml_probability' in vals:
            prob = vals['ml_probability']
            if prob >= 75:
                vals['priority'] = '3'
            elif prob >= 50:
                vals['priority'] = '2'
            elif prob >= 25:
                vals['priority'] = '1'
            else:
                vals['priority'] = '0'
        return super().write(vals)

